// Butter Studio menu: dev/butter-studio.json -> photos in public/img/butter/ and the menu in src/app.js.
//   node dev/butter-studio.mjs            photos (only missing ones) + menu
//   node dev/butter-studio.mjs --photos   download every photo again
// Standard menu (order.thebutterstudio.com, about 3 days) and custom designs (celebrate.thebutterstudio.com,
// 5-7 working days). Prices are their public prices with status 'demo' until agreed; then run npm run catalogue.
// The fully bespoke "Custom cake" group (bs-custom) is kept as it is.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'dev/butter-studio.json'), 'utf8'));
const dir = path.join(root, 'public/img/butter');
fs.mkdirSync(dir, { recursive: true });

const slug = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/\(([^)]*)\)/g, '$1').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 44);
const items = [
  ...data.standard.map((r) => ({ kind: 'standard', id: 'bs-' + slug(r[1]), r })),
  ...data.custom.map((r) => ({ kind: 'custom', id: 'bsc-' + slug(r[1]), r })),
];
const ids = new Set(); for (const it of items) { if (ids.has(it.id)) throw new Error('duplicate id ' + it.id); ids.add(it.id); }

// Photos: downloaded once, resized to 640 px JPEG in a headless browser (Playwright is already a dev dependency)
const missing = items.filter((it) => process.argv.includes('--photos') || !fs.existsSync(path.join(dir, it.id + '.jpg')));
if (missing.length) {
  const { chromium } = await import(pathToFileURL(path.join(root, 'node_modules/playwright/index.mjs')).href);
  const browser = await chromium.launch(); const page = await browser.newPage();
  for (const it of missing) {
    const res = await fetch(it.r[5]); if (!res.ok) throw new Error(`${it.id}: photo ${res.status}`);
    const type = res.headers.get('content-type') || 'image/jpeg', b64 = Buffer.from(await res.arrayBuffer()).toString('base64');
    const jpg = await page.evaluate(async ([src]) => {
      const im = new Image(); im.src = src; await im.decode();
      const s = Math.min(1, 640 / Math.max(im.naturalWidth, im.naturalHeight)), c = document.createElement('canvas');
      c.width = Math.round(im.naturalWidth * s); c.height = Math.round(im.naturalHeight * s);
      const x = c.getContext('2d'); x.fillStyle = '#fff'; x.fillRect(0, 0, c.width, c.height); x.drawImage(im, 0, 0, c.width, c.height);
      return c.toDataURL('image/jpeg', 0.8).split(',')[1];
    }, [`data:${type};base64,${b64}`]);
    fs.writeFileSync(path.join(dir, it.id + '.jpg'), Buffer.from(jpg, 'base64'));
    console.log('photo', it.id);
  }
  await browser.close();
}

// Menu lines for src/app.js
const q = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const line = ({ kind, id, r: [sec, name, cents, from, cap] }) => {
  const cond = kind === 'standard'
    ? ['Order at least 3 days ahead', 'Delivery from $16, confirmed in your quote']
    : ['Order 5–7 working days ahead', 'Design as pictured; changes are priced as a custom order', 'Delivery from $16, confirmed in your quote'];
  if (from) cond.unshift('Price is for the smallest size; larger sizes are priced in your quote');
  return `    {id:${q(id)}, sec:${q(kind === 'custom' ? 'Custom designs: ' + sec : sec)}, cat:'cake', name:${q(name)}, vendor:'Butter Studio', status:'demo', basis:'cake', price:${cents}, rec:0, img:${q('img/butter/' + id + '.jpg')}, cap:${q(cap)}, inc:[${q(cap)}], cond:[${cond.map(q).join(',')}]},`;
};
const START = '    // Butter Studio menu: generated by dev/butter-studio.mjs from dev/butter-studio.json. Edit the JSON, then run it.';
const END = '    // End of the Butter Studio menu';
const A = path.join(root, 'src/app.js');
let js = fs.readFileSync(A, 'utf8');
if (js.includes(START)) js = js.slice(0, js.indexOf(START)) + js.slice(js.indexOf(END) + END.length + 1);
else js = js.split('\n').filter((l) => !/^\s*\{id:'bs-(?!custom)[a-z0-9-]+'/.test(l)).join('\n'); // first run: drop the old demo items
const anchor = js.split('\n').find((l) => l.includes("{id:'bs-custom-12'"));
if (!anchor) throw new Error('bs-custom-12 not found in src/app.js');
js = js.replace(anchor + '\n', anchor + '\n' + [START, ...items.map(line), END].join('\n') + '\n');
fs.writeFileSync(A, js);
console.log(`src/app.js: ${items.length} Butter Studio items (${data.standard.length} standard, ${data.custom.length} custom designs)`);
